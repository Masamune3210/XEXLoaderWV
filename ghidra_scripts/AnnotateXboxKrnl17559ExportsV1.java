    private long u32(Memory mem, Address addr) throws MemoryAccessException {
        long x = 0;
        for (int i = 0; i < 4; i++) {
            x |= (mem.getByte(addr.add(i)) & 0xFFL) << (i * 8);
        }
        return x;
    }

    private Address va(long value) {
        return currentProgram.getAddressFactory().getDefaultAddressSpace().getAddress(value);
    }

    private boolean hasLabel(SymbolTable symbols, Address addr, String name) {
        for (Symbol symbol : symbols.getSymbols(addr)) {
            if (symbol.getName().equals(name)) return true;
        }
        return false;
    }

    @Override
    public void run() throws Exception {
        if (currentProgram.getImageBase().getOffset() != BASE) {
            printerr(String.format("STOP: Expected kernel image base %08X, found %s. Verify the PE import mapping.",
                BASE, currentProgram.getImageBase()));
            return;
        }
        String actualHash = currentProgram.getExecutableSHA256();
        if (actualHash != null && !actualHash.isEmpty() &&
            !actualHash.equalsIgnoreCase(VERIFIED_SHA256)) {
            printerr("STOP: Program's original executable SHA256 does not match the verified retail 17559 kernel: " + actualHash);
            return;
        }

        Memory mem = currentProgram.getMemory();
        Address dir = va(BASE + EXPORT_DIR_RVA);
        long ordinalBase = u32(mem, dir.add(16));
        long entryCount = u32(mem, dir.add(20));
        long namedCount = u32(mem, dir.add(24));
        long functionTableRva = u32(mem, dir.add(28));
        if (ordinalBase != 1 || entryCount != EXPORT_COUNT ||
            namedCount != 0 || functionTableRva != 0x15E2CL) {
            printerr(String.format("STOP: Export directory mismatch: base=%d count=%d named=%d table=%08X",
                ordinalBase, entryCount, namedCount, functionTableRva));
            return;
        }

        SymbolTable symbols = currentProgram.getSymbolTable();
        int codeExports = 0, dataExports = 0, emptySlots = 0;
        int created = 0, renamedFunctions = 0, alreadyNamed = 0, errors = 0, unknownNames = 0;
        int oddLocations = 0;
        for (int ordinal = 1; ordinal <= EXPORT_COUNT; ordinal++) {
            monitor.checkCancelled();
            long rva = u32(mem, va(BASE + functionTableRva + (ordinal - 1L) * 4));
            if (rva == 0) { emptySlots++; continue; }
            Address dest = va(BASE + rva);
            MemoryBlock block = mem.getBlock(dest);
            if (block == null) {
                printerr(String.format("Missing mapped export: ordinal %d RVA %08X", ordinal, rva));
                errors++;
                continue;
            }
            if (block.isExecute()) codeExports++; else dataExports++;

            String name = ordinal < KNOWN.length ? KNOWN[ordinal] : null;
            if (name == null) {
                name = String.format("xboxkrnl_ordinal_%03d", ordinal);
                unknownNames++;
            }
            if (hasLabel(symbols, dest, name)) { alreadyNamed++; continue; }

            try {
                Function function = currentProgram.getFunctionManager().getFunctionAt(dest);
                if (function != null && block.isExecute() &&
                    (function.getSymbol().getSource() != SourceType.USER_DEFINED) &&
                    (function.getSymbol().getSource() == SourceType.DEFAULT ||
                     function.getName().startsWith("FUN_") ||
                     function.getName().startsWith("Ordinal_"))) {
                    function.setName(name, SourceType.ANALYSIS);
                    renamedFunctions++;
                } else {
                    // Secondary labels preserve user-renamed functions and existing symbols.
                    createLabel(dest, name, false);
                    created++;
                }
                if (block.isExecute() &&
                    currentProgram.getFunctionManager().getFunctionContaining(dest) != null &&
                    currentProgram.getFunctionManager().getFunctionAt(dest) == null) {
                    oddLocations++;
                    if (oddLocations <= 25)
                        printerr("Export points inside a different function: ordinal " + ordinal + " @ " + dest);
                }
            } catch (Exception ex) {
                errors++;
                if (errors <= 25) printerr("Ordinal " + ordinal + " @ " + dest + ": " + ex);
            }
        }

        println("Retail Xbox 360 xboxkrnl.exe 17559 export annotations:");
        println("Expected slots / empty: " + EXPORT_COUNT + " / " + emptySlots);
        println("Executable / data exports: " + codeExports + " / " + dataExports);
        println("New labels / renamed default functions / already present: " + created + " / " + renamedFunctions + " / " + alreadyNamed);
        println("Generic unknown-ordinal labels: " + unknownNames);
        println("Overlaps into existing functions / errors: " + oddLocations + " / " + errors);
        println("Preserved: image bytes, undefined code, existing user names, signatures, datatypes.");
    }
